const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('pet', Object.freeze({
  action: name => ipcRenderer.invoke('pet:action', String(name)),
  modelUrl: () => ipcRenderer.invoke('pet:model'),
  modelBundle: () => ipcRenderer.invoke('pet:model-bundle'),
  validation: () => ipcRenderer.invoke('pet:validation'),
  showcase: () => ipcRenderer.invoke('pet:showcase'),
  rigCheck: () => ipcRenderer.invoke('pet:rig-check'),
  rigResult: info => ipcRenderer.send('pet:rig-result',info),
  previewVideo: value => ipcRenderer.invoke('pet:preview-video',value),
  capture: (mode,png) => ipcRenderer.send('pet:capture',{mode,png}),
  config: () => ipcRenderer.invoke('gpt:config'),
  save: (key,model) => ipcRenderer.invoke('gpt:save', {key:String(key),model:String(model)}),
  clearKey: () => ipcRenderer.invoke('gpt:clear-key'),
  reply: (text,history) => ipcRenderer.invoke('gpt:reply',{text,history}),
  cancel: () => ipcRenderer.invoke('gpt:cancel'),
  dragStart: () => ipcRenderer.send('pet:drag-start'),
  dragEnd: () => ipcRenderer.invoke('pet:drag-end'),
  dragCancel: () => ipcRenderer.send('pet:drag-cancel'),
  clickThrough: enabled => ipcRenderer.send('pet:click-through',Boolean(enabled)),
  onState: callback => { ipcRenderer.on('pet:state',(_e,state)=>callback(state)); },
  onGaze: callback => { ipcRenderer.on('pet:gaze',(_e,gaze)=>callback(gaze)); },
  onOpenSettings: callback => { ipcRenderer.on('chat:settings',()=>callback()); },
  ready: info => ipcRenderer.send('pet:ready',info),
}));
